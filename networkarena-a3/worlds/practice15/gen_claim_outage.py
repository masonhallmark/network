#!/usr/bin/env python3
"""gen_claim_outage.py: ten practice claim runs for the "link 0-5 goes down and comes back" egg ("egg 34"), in worlds/practice15/claim_outage/.

The egg as seen in truth run 2: switch 0 logs link 0-5 coming back at 36.00 s; it heard switch 5 normally at 28.56 s, so the outage began between 28.6 and 36.0 s and lasted up to about 7 s.
  on  (true):  link 0-5 goes down for 3-7 s and comes back, starting at different moments
  off:         link 0-5 never fails
  near misses: 0-5 goes down and stays down; 0-5 down for only 1 s; another link (5-10, 6-11, 4-9) has the same 6 s outage; switch 0's other link (0-1) has it.
Every other anomaly of the truth logs is on in every run (1-2 and 13-14 one-way slow, 1-6 flapping twice, 12-13 and 7-12 lossy, 6-7 cut). Guesses, not knowledge.
"""
import os, random, sys
here = os.path.dirname(os.path.abspath(__file__))
outdir = os.path.join(here, "claim_outage")
os.makedirs(outdir, exist_ok=True)
src = open(os.path.join(here, "gen15.py")).read()
src = src[: src.index("head = '''")]
# (run, on, load, variant, extra plants as (kind, a, b, at_ms, for_ms) tuples)
RUNS = [
    (1, True, 1.0, "outage", [("fail", 0, 5, 30000, 6000)]),
    (2, True, 1.25, "outage", [("fail", 0, 5, 31000, 4900)]),
    (3, True, 1.5, "outage", [("fail", 0, 5, 29500, 3000)]),
    (4, True, 1.0, "early", [("fail", 0, 5, 8000, 6000)]),
    (5, True, 1.25, "mid", [("fail", 0, 5, 20000, 7000)]),
    (6, False, 1.0, "off", []),
    (7, False, 1.25, "stays", [("fail", 0, 5, 30000, None)]),
    (8, False, 1.5, "brief", [("fail", 0, 5, 30000, 1000)]),
    (9, False, 1.0, "other", [("fail", 5, 10, 30000, 6000), ("fail", 6, 11, 12000, 6000)]),
    (10, False, 1.5, "01", [("fail", 0, 1, 30000, 6000)]),
]
def plant(**kw):
    return "[[plant]]\n" + "".join(f'{k} = {v if not isinstance(v, str) else chr(34) + v + chr(34)}\n' for k, v in kw.items()) + "\n"
answers = ['# The practice claim runs for egg 34 (link 0-5 outage), and their answers. Generated: do not edit.\n\n[[egg]]\nn = 34\nname = "The outage"\ncategory = "Failure"\n']
for run, on, load, variant, extra in RUNS:
    seed = 3800 + run
    ns: dict = {}
    exec(src.replace("random.Random(15)", f"random.Random({seed})"), ns)
    pair = ns["pair"]
    rng = random.Random(seed * 7)
    apps, links = dict(ns["apps"]), ns["links"]
    j = lambda ms: ms + rng.randint(-400, 400)
    base = [
        plant(kind="link_delay", a=13, b=14, a_to_b_us=25000, b_to_a_us=500),
        plant(kind="link_delay", a=1, b=2, a_to_b_us=2000, b_to_a_us=30000),
        plant(kind="wire_loss", a=12, b=13, loss_pct=40.0, start_ms=j(7000), stop_ms=j(29000)),
        '[[plant]]\nkind = "link_capacity"\na = 6\nb = 7\nsteps = [[0, 10], [%d, 3]]\n\n' % j(12000),
        plant(kind="fail", a=1, b=6, at_ms=j(5910), for_ms=1630),
        plant(kind="fail", a=1, b=6, at_ms=j(17950), for_ms=1630),
        plant(kind="wire_loss", a=7, b=12, loss_pct=10.0, start_ms=0),
    ]
    mine = []
    for kind, a, b, at, dur in extra:
        if kind == "fail":
            kw = dict(kind="fail", a=a, b=b, at_ms=j(at))
            if dur is not None: kw["for_ms"] = dur
            mine.append(plant(**kw))
        else:
            mine.append(plant(kind="wire_loss", a=a, b=b, loss_pct=50.0 if run == 10 else 30.0, start_ms=0))
    plants = "".join(base + mine)
    head = f'''# A3 practice claim run (link 0-5 outage, egg 34), run {run} of 10. Generated by gen_claim_outage.py: do not edit.
# The answer is in answers.toml. Load {load}.
[world]
name = "a3-claim-flap-r{run:02}"
seed = {seed}
version = 1
family = "harness"

[params]
link_capacity_mbps = 10
link_latency_us = 500
queue_capacity_bytes = 40000
warmup_ms = 3000
duration_ms = 40000
delivery_floor_pct = 0.0
packet_size_bytes = 1000
control_delay_us = 2000

'''
    body = "".join(f"[[switch]]\nid = {i}\n\n" for i in range(15)) + "".join(f"[[link]]\na = {a}\nb = {b}\n\n" for a, b in links) + "\n".join(apps[i] for i in sorted(apps))
    tail = '''
[workload]
kind = "mixed"
size_bytes = 1000

[observe]
punt_events_per_s = 80
punt_backlog = 64
export_bytes_per_s = 16000
export_burst_bytes = 8000

[harness]
keepalive_ms = 100
log_cap_bytes = 24576

'''
    open(os.path.join(outdir, f"run{run:02}.toml"), "w").write(head + body + tail + plants)
    answers.append(f'\n[[run]]\negg = 34\nrun = {run}\non = {"true" if on else "false"}\nload = {load}\nworld = "run{run:02}.toml"\n')
open(os.path.join(outdir, "answers.toml"), "w").write("".join(answers))
print("wrote 10 runs to", outdir)

#!/usr/bin/env python3
"""gen_claim_ttl.py: ten practice claim runs for the TTL-ladder egg ("egg 31, The traceroute"), in worlds/practice15/claim_ttl/.

Modelled on the provided practice eggs (worlds/practice/README.md): ten runs per egg, about half with the egg, each dealt afresh (new address
ranges and hosts, rates, start order, and the moment the egg starts), loads cycling through 1.0, 1.25 and 1.5. The run is the 15-switch real map.

The egg, as seen in truth runs 1 and 2: a customer at switch 4 (its range is named Mapper) sends 64-byte UDP packets whose TTL cycles through small values.
  on  (true):  Mapper's packets start at TTL 1..N cyclically, N between 8 and 10
  off:         Mapper sends the same packets at the normal TTL
  near misses: (a) every Mapper packet starts at one low TTL (3 or 5), no ladder;
               (b) Mapper is normal but another customer, at switch 10, sends the ladder.
These are my guesses at what a grader's runs look like, not knowledge of them.

Every other anomaly seen in the truth logs is switched on in every run, as the handout says the claim runs do for the other eggs: link 1-6 down twice for 1.63 s,
link 13-14 25 ms one way, link 1-2 30 ms one way and 2 ms the other, link 6-7 cut to 3 Mbit/s, link 12-13 losing 40%, link 0-5 down for a long time, link 7-12 losing 10%.
"""
import os, random, sys
here = os.path.dirname(os.path.abspath(__file__))
outdir = os.path.join(here, "claim_ttl")
os.makedirs(outdir, exist_ok=True)
src = open(os.path.join(here, "gen15.py")).read()
src = src[: src.index("head = '''")]
# (run, on, load, variant, ladder, start_ms)
RUNS = [
    (1, False, 1.25, "off", 0, 2500),
    (2, True, 1.0, "ladder", 8, 4000),
    (3, True, 1.5, "ladder", 10, 1500),
    (4, False, 1.0, "constant", 5, 3000),
    (5, True, 1.25, "ladder", 9, 6500),
    (6, False, 1.0, "other", 8, 2000),
    (7, False, 1.25, "off", 0, 5000),
    (8, True, 1.5, "ladder", 8, 14000),
    (9, False, 1.5, "constant", 3, 1000),
    (10, True, 1.0, "ladder", 10, 0),
]
def plant(**kw):
    return "[[plant]]\n" + "".join(f'{k} = {v if not isinstance(v, str) else chr(34) + v + chr(34)}\n' for k, v in kw.items()) + "\n"
answers = ['# The practice claim runs for egg 31 (the TTL ladder), and their answers. Generated: do not edit.\n\n[[egg]]\nn = 31\nname = "The traceroute"\ncategory = "Traffic"\n']
for run, on, load, variant, n, start in RUNS:
    seed = 3100 + run
    ns: dict = {}
    exec(src.replace("random.Random(15)", f"random.Random({seed})"), ns)
    pair = ns["pair"]
    rng = random.Random(seed * 7)
    rate = round(rng.uniform(0.03, 0.08), 3)
    proto = 'proto = "udp"\n'
    if variant == "ladder":
        pair(4, 10, "Mapper", "ping", rate, size=64, extra=f'{proto}ttl_ladder = {n}\nstart_ms = {start}\n')
    elif variant == "constant":
        pair(4, 10, "Mapper", "ping", rate, size=64, extra=f'{proto}ttl_start = {n}\nstart_ms = {start}\n')
    else:
        pair(4, 10, "Mapper", "ping", rate, size=64, extra=f'{proto}start_ms = {start}\n')
        if variant == "other":
            pair(10, 2, "Mapper-2", "ping", rate, size=64, extra=f'{proto}ttl_ladder = {n}\nstart_ms = {start}\n')
    apps, links = dict(ns["apps"]), ns["links"]
    j = lambda ms: ms + rng.randint(-400, 400)
    plants = "".join([
        plant(kind="fail", a=1, b=6, at_ms=j(5910), for_ms=1630),
        plant(kind="fail", a=1, b=6, at_ms=j(17950), for_ms=1630),
        plant(kind="link_delay", a=13, b=14, a_to_b_us=25000, b_to_a_us=500),
        plant(kind="link_delay", a=1, b=2, a_to_b_us=2000, b_to_a_us=30000),
        plant(kind="wire_loss", a=12, b=13, loss_pct=40.0, start_ms=j(7000), stop_ms=j(29000)),
        '[[plant]]\nkind = "link_capacity"\na = 6\nb = 7\nsteps = [[0, 10], [%d, 3]]\n\n' % j(12000),
        plant(kind="fail", a=0, b=5, at_ms=j(14000), for_ms=22000),
        plant(kind="wire_loss", a=7, b=12, loss_pct=10.0, start_ms=0),
    ])
    head = f'''# A3 practice claim run (the TTL ladder, egg 31), run {run} of 10. Generated by gen_claim_ttl.py: do not edit.
# The answer is in answers.toml. Load {load}.
[world]
name = "a3-claim-ttl-r{run:02}"
seed = {seed}
version = 1
family = "harness"

[params]
link_capacity_mbps = 10
link_latency_us = 500
queue_capacity_bytes = 40000
warmup_ms = 3000
duration_ms = 40000
delivery_floor_pct = 0.0
packet_size_bytes = 1000
control_delay_us = 2000

'''
    body = "".join(f"[[switch]]\nid = {i}\n\n" for i in range(15)) + "".join(f"[[link]]\na = {a}\nb = {b}\n\n" for a, b in links) + "\n".join(apps[i] for i in sorted(apps))
    tail = '''
[workload]
kind = "mixed"
size_bytes = 1000

[observe]
punt_events_per_s = 80
punt_backlog = 64
export_bytes_per_s = 16000
export_burst_bytes = 8000

[harness]
keepalive_ms = 100
log_cap_bytes = 24576

'''
    open(os.path.join(outdir, f"run{run:02}.toml"), "w").write(head + body + tail + plants)
    answers.append(f'\n[[run]]\negg = 31\nrun = {run}\non = {"true" if on else "false"}\nload = {load}\nworld = "run{run:02}.toml"\n')
open(os.path.join(outdir, "answers.toml"), "w").write("".join(answers))
print("wrote 10 runs to", outdir)

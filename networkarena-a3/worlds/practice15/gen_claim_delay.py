#!/usr/bin/env python3
"""gen_claim_delay.py: ten practice claim runs for the "link 1-2 has a slow direction" egg ("egg 33"), in worlds/practice15/claim_delay/.

The egg as seen in truth run 2: switch 1 hears switch 2 at 30.0 ms and switch 2 hears switch 1 at 2.0 ms (others 0.5 ms): a link_delay plant on 1-2.
  on  (true):  link 1-2 delay 30 ms (or 25-40) from 2 to 1 and 0.5-2 ms from 1 to 2
  off:         link 1-2 has the normal 0.5 ms both ways
  near misses: 30 ms both ways; slow the other way round (1 to 2); link 1-2 only congested (capacity cut to 1 Mbit/s); another link (5-6) has the one-way delay.
Every other anomaly of the truth logs is on in every run (13-14 slow one way, 1-6 flapping, 12-13 and 7-12 lossy, 6-7 cut, 0-5 down).
My guesses at the grader's runs, not knowledge of them.
"""
import os, random, sys
here = os.path.dirname(os.path.abspath(__file__))
outdir = os.path.join(here, "claim_delay")
os.makedirs(outdir, exist_ok=True)
src = open(os.path.join(here, "gen15.py")).read()
src = src[: src.index("head = '''")]
RUNS = [
    (1, True, 1.0, "asym", [("link_delay", 1, 2, 2000, 30000)]),
    (2, True, 1.25, "asym", [("link_delay", 1, 2, 500, 40000)]),
    (3, True, 1.5, "asym", [("link_delay", 1, 2, 1000, 25000)]),
    (4, True, 1.0, "asym", [("link_delay", 1, 2, 2000, 30000)]),
    (5, True, 1.25, "asym", [("link_delay", 1, 2, 500, 35000)]),
    (6, False, 1.0, "off", []),
    (7, False, 1.25, "symmetric", [("link_delay", 1, 2, 30000, 30000)]),
    (8, False, 1.5, "reversed", [("link_delay", 1, 2, 30000, 2000)]),
    (9, False, 1.0, "congested", [("link_capacity", 1, 2, 0, 0)]),
    (10, False, 1.5, "other", [("link_delay", 5, 6, 2000, 30000)]),
]
def plant(**kw):
    return "[[plant]]\n" + "".join(f'{k} = {v if not isinstance(v, str) else chr(34) + v + chr(34)}\n' for k, v in kw.items()) + "\n"
answers = ['# The practice claim runs for egg 33 (link 1-2 delay), and their answers. Generated: do not edit.\n\n[[egg]]\nn = 33\nname = "The slow side"\ncategory = "Failure"\n']
for run, on, load, variant, extra in RUNS:
    seed = 3400 + run
    ns: dict = {}
    exec(src.replace("random.Random(15)", f"random.Random({seed})"), ns)
    pair = ns["pair"]
    rng = random.Random(seed * 7)
    apps, links = dict(ns["apps"]), ns["links"]
    j = lambda ms: ms + rng.randint(-400, 400)
    base = [
        plant(kind="link_delay", a=13, b=14, a_to_b_us=25000, b_to_a_us=500),
        plant(kind="wire_loss", a=12, b=13, loss_pct=40.0, start_ms=j(7000), stop_ms=j(29000)),
        '[[plant]]\nkind = "link_capacity"\na = 6\nb = 7\nsteps = [[0, 10], [%d, 3]]\n\n' % j(12000),
        plant(kind="fail", a=0, b=5, at_ms=j(14000), for_ms=22000),
        plant(kind="wire_loss", a=7, b=12, loss_pct=10.0, start_ms=0),
    ]
    base.append(plant(kind="fail", a=1, b=6, at_ms=j(5910), for_ms=1630)); base.append(plant(kind="fail", a=1, b=6, at_ms=j(17950), for_ms=1630))
    mine = []
    for kind, a, b, at, dur in extra:
        if kind == "link_delay":
            mine.append(plant(kind="link_delay", a=a, b=b, a_to_b_us=at, b_to_a_us=dur))
        else:
            mine.append('[[plant]]\nkind = "link_capacity"\na = 1\nb = 2\nsteps = [[0, 10], [%d, 1]]\n\n' % j(6000))
    plants = "".join(base + mine)
    head = f'''# A3 practice claim run (link 1-2 slow direction, egg 33), run {run} of 10. Generated by gen_claim_delay.py: do not edit.
# The answer is in answers.toml. Load {load}.
[world]
name = "a3-claim-flap-r{run:02}"
seed = {seed}
version = 1
family = "harness"

[params]
link_capacity_mbps = 10
link_latency_us = 500
queue_capacity_bytes = 40000
warmup_ms = 3000
duration_ms = 40000
delivery_floor_pct = 0.0
packet_size_bytes = 1000
control_delay_us = 2000

'''
    body = "".join(f"[[switch]]\nid = {i}\n\n" for i in range(15)) + "".join(f"[[link]]\na = {a}\nb = {b}\n\n" for a, b in links) + "\n".join(apps[i] for i in sorted(apps))
    tail = '''
[workload]
kind = "mixed"
size_bytes = 1000

[observe]
punt_events_per_s = 80
punt_backlog = 64
export_bytes_per_s = 16000
export_burst_bytes = 8000

[harness]
keepalive_ms = 100
log_cap_bytes = 24576

'''
    open(os.path.join(outdir, f"run{run:02}.toml"), "w").write(head + body + tail + plants)
    answers.append(f'\n[[run]]\negg = 33\nrun = {run}\non = {"true" if on else "false"}\nload = {load}\nworld = "run{run:02}.toml"\n')
open(os.path.join(outdir, "answers.toml"), "w").write("".join(answers))
print("wrote 10 runs to", outdir)

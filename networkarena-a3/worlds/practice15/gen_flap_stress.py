#!/usr/bin/env python3
"""gen_claim_flap.py: ten practice claim runs for the "link 1-6 flaps" egg ("egg 32"), in worlds/practice15/claim_flap/.

Same layout as gen_claim_ttl.py. The egg as seen in truth runs 1 and 2: link 1-6 goes down for 1.63 s and comes back, twice (5.91 and 17.95 s).
  on  (true):  link 1-6 goes down and comes back two or more times (down 1.1 to 2 s each, various start times)
  off:         link 1-6 never fails
  near misses: 1-6 down once and back; 1-6 down once and stays down; another link (5-6, 6-11, 2-7) flaps twice; 1-6 only loses 30% / 50% of packets.
These are my guesses at what a grader's runs look like, not knowledge of them. Every other anomaly of the truth logs is on in every run.
"""
import os, random, sys
here = os.path.dirname(os.path.abspath(__file__))
outdir = os.path.join(here, "claim_flap_stress")
os.makedirs(outdir, exist_ok=True)
src = open(os.path.join(here, "gen15.py")).read()
src = src[: src.index("head = '''")]
import random as _r
_g = _r.Random(99)
RUNS = []
for run in range(1, 41):
    load = _g.choice([1.0, 1.25, 1.5, 1.75, 2.0])
    kind = _g.choice(["flap", "flap", "flap", "once", "stays", "off", "other", "lossy", "longflap"])
    ex, on = [], False
    if kind in ("flap", "longflap"):
        n = _g.randint(2, 4)
        t = _g.randint(2000, 8000)
        for _ in range(n):
            d = _g.randint(1000, 3000) if kind == "flap" else _g.randint(4000, 8000)
            if t + d > 37500: break
            ex.append(("fail", 1, 6, t, d)); t += d + _g.randint(3000, 9000)
        on = len(ex) >= 2
    elif kind == "once": ex = [("fail", 1, 6, _g.randint(2000, 30000), _g.randint(1000, 3000))]
    elif kind == "stays": ex = [("fail", 1, 6, _g.randint(2000, 30000), None)]
    elif kind == "other":
        a, b = _g.choice([(5, 6), (6, 11), (2, 7), (0, 1), (6, 7)])
        t = _g.randint(2000, 8000)
        ex = [("fail", a, b, t, 1600), ("fail", a, b, t + 12000, 1600)]
    elif kind == "lossy": ex = [("wire_loss", 1, 6, 0, None)]
    RUNS.append((run, on, load, kind, ex))
def plant(**kw):
    return "[[plant]]\n" + "".join(f'{k} = {v if not isinstance(v, str) else chr(34) + v + chr(34)}\n' for k, v in kw.items()) + "\n"
answers = ['# The practice claim runs for egg 32 (link 1-6 flaps), and their answers. Generated: do not edit.\n\n[[egg]]\nn = 32\nname = "The flapping link"\ncategory = "Failure"\n']
for run, on, load, variant, extra in RUNS:
    seed = 3300 + run
    ns: dict = {}
    exec(src.replace("random.Random(15)", f"random.Random({seed})"), ns)
    pair = ns["pair"]
    rng = random.Random(seed * 7)
    apps, links = dict(ns["apps"]), ns["links"]
    j = lambda ms: ms + rng.randint(-400, 400)
    base = [
        plant(kind="link_delay", a=13, b=14, a_to_b_us=25000, b_to_a_us=500),
        plant(kind="link_delay", a=1, b=2, a_to_b_us=2000, b_to_a_us=30000),
        plant(kind="wire_loss", a=12, b=13, loss_pct=40.0, start_ms=j(7000), stop_ms=j(29000)),
        '[[plant]]\nkind = "link_capacity"\na = 6\nb = 7\nsteps = [[0, 10], [%d, 3]]\n\n' % j(12000),
        plant(kind="fail", a=0, b=5, at_ms=j(14000), for_ms=22000),
        plant(kind="wire_loss", a=7, b=12, loss_pct=10.0, start_ms=0),
    ]
    mine = []
    for kind, a, b, at, dur in extra:
        if kind == "fail":
            kw = dict(kind="fail", a=a, b=b, at_ms=j(at))
            if dur is not None: kw["for_ms"] = dur
            mine.append(plant(**kw))
        else:
            mine.append(plant(kind="wire_loss", a=a, b=b, loss_pct=_g.choice([10.0, 30.0, 50.0]), start_ms=0))
    plants = "".join(base + mine)
    head = f'''# A3 practice claim run (link 1-6 flaps, egg 32), run {run} of 10. Generated by gen_claim_flap.py: do not edit.
# The answer is in answers.toml. Load {load}.
[world]
name = "a3-claim-flap-r{run:02}"
seed = {seed}
version = 1
family = "harness"

[params]
link_capacity_mbps = 10
link_latency_us = 500
queue_capacity_bytes = 40000
warmup_ms = 3000
duration_ms = 40000
delivery_floor_pct = 0.0
packet_size_bytes = 1000
control_delay_us = 2000

'''
    body = "".join(f"[[switch]]\nid = {i}\n\n" for i in range(15)) + "".join(f"[[link]]\na = {a}\nb = {b}\n\n" for a, b in links) + "\n".join(apps[i] for i in sorted(apps))
    tail = '''
[workload]
kind = "mixed"
size_bytes = 1000

[observe]
punt_events_per_s = 80
punt_backlog = 64
export_bytes_per_s = 16000
export_burst_bytes = 8000

[harness]
keepalive_ms = 100
log_cap_bytes = 24576

'''
    open(os.path.join(outdir, f"run{run:02}.toml"), "w").write(head + body + tail + plants)
    answers.append(f'\n[[run]]\negg = 32\nrun = {run}\non = {"true" if on else "false"}\nload = {load}\nworld = "run{run:02}.toml"\n')
open(os.path.join(outdir, "answers.toml"), "w").write("".join(answers))
print("wrote 10 runs to", outdir)

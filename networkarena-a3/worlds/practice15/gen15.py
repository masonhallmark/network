# Generates worlds/practice15/run-{a,b,c}.toml: the real 3x5 grid with a busier customer mix and
# one plant of every kind the simulator knows. Not the hidden network, only the same shape.
import random
links = [(0,1),(0,5),(1,2),(1,6),(2,3),(2,7),(3,4),(3,8),(4,9),(5,6),(5,10),(6,7),(6,11),(7,8),(7,12),(8,9),(8,13),(9,14),(10,11),(11,12),(12,13),(13,14)]
rng = random.Random(15)
used = set()
def prefix():
    while True:
        p = (rng.randint(1, 60), rng.randint(0, 255))
        if p not in used:
            used.add(p); return f"10.{p[0]}.{p[1]}.0/24"
apps = []
def pair(sw_a, sw_b, name, preset, rate, law=None, size=None, both=False, extra=""):
    ia = 100 + len(apps); ib = ia + 1
    pa, pb = prefix(), prefix()
    def row(i, sw, p, peer, sender, nm):
        s = f'[[app]]\nid = {i}\nswitch = {sw}\nprefix = "{p}"\nhosts = [{rng.randint(2,250)}]\nname = "{nm}"\n'
        if sender:
            s += f'preset = "{preset}"\npeer = {peer}\n'
            if rate: s += f'rate_mbps = {rate}\n'
            if law: s += f'law = "{law}"\n'
            if size: s += f'size_bytes = {size}\n'
            s += extra
        return s
    apps.append((ia, row(ia, sw_a, pa, ib, True, name)))
    apps.append((ib, row(ib, sw_b, pb, ia, both, name if both else name + "'s peer")))
    return ia
nf1 = pair(0, 14, "Netflix", "netflix", 1.7, "aimd")
nf2 = pair(4, 10, "Netflix", "netflix", 2.0, "aimd")
nf3 = pair(2, 12, "Netflix", "netflix", 1.5, "aimd")
pair(1, 13, "Fortnite", "fortnite", 0.36, size=200, both=True)
pair(5, 9, "Fortnite", "fortnite", 0.37, size=200, both=True)
pair(3, 11, "Steam", "steam", None, "aimd")
pair(6, 8, "Steam", "steam", None, "aimd")
am1 = pair(0, 8, "Amazon", "amazon", 0.8, extra="on_ms = 8000\noff_ms = 8000\nstart_ms = 0\n")
am2 = pair(14, 6, "Amazon", "amazon", 0.9, extra="on_ms = 6000\noff_ms = 10000\nstart_ms = 2000\n")
pair(7, 2, "Jane Street", "jane_street", 0.10, size=200)
pair(12, 4, "Ping", "ping", 0.02, size=100)

for n, load in (("a", 1.0), ("b", 1.25), ("c", 1.5)):
    out = head.format(load=load, n=n, seed=15 + ord(n)) + "".join(f"[[switch]]\nid = {i}\n\n" for i in range(15))
    out += "".join(f"[[link]]\na = {a}\nb = {b}\n\n" for a, b in links)
    out += "\n".join(r for _, r in apps)
    out += tail.format(nf2=nf2, am2=am2, nf3=nf3)
